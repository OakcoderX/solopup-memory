export function planReleaseSync({manifest,receipt,index,documents}){
  validateReceipt(manifest,receipt)
  const next=structuredClone(index),entry=next.plugins?.find(p=>p.name==='solopup-memory')
  if(!entry||!Array.isArray(entry.versions))throw Error('market entry missing')
  const seen=new Set()
  for(const v of entry.versions){compareBeta(v.version,v.version);if(seen.has(v.version))throw Error('duplicate market version; inspect manually');seen.add(v.version)}
  const existing=entry.versions.find(v=>v.version===manifest.version)
  if(existing&& (existing.source?.type!=='npm'||existing.source.registry!==registry+'/'))throw Error('existing market source differs; inspect manually')
  if(!existing)entry.versions.push({version:manifest.version,publishTimestamp:Math.floor(Date.parse(receipt.publishedAt)/1000),engines:manifest.engines?.dsh?{dsh:manifest.engines.dsh}:{},source:{type:'npm',registry:registry+'/'}})
  entry.versions.sort((a,b)=>compareBeta(b.version,a.version))
  const stale=entry.versions[0].version!==manifest.version
  const files={'market/index.json':JSON.stringify(next,null,2)+'\n'}
  if(!stale){
    for(const [path,body] of Object.entries(installBlocks))files[path]=checkManagedDocument(documents[path],body)
    files['docs/releases/current-beta.md']=currentReleaseDocument(manifest)
  }
  return {files,stale,currentVersion:entry.versions[0].version}
}
export function syncReleaseFiles(manifest,receipt,root=process.cwd()){
  const read=p=>readFileSync(join(root,p),'utf8')
  const documents=Object.fromEntries(Object.keys(installBlocks).map(p=>[p,read(p)]))
  const plan=planReleaseSync({manifest,receipt,index:JSON.parse(read('market/index.json')),documents})
  // Plan and validate everything before the first local write. Never touch historical reports.
  for(const [path,content] of Object.entries(plan.files)){mkdirSync(dirname(join(root,path)),{recursive:true});writeFileSync(join(root,path),content)}
  return plan
}
