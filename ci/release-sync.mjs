export const repository='OakcoderX/solopup-memory'
export const registry='https://registry.npmjs.org'
const beta=/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)-beta\.(0|[1-9]\d*)$/
export function compareBeta(a,b){
  const parts=v=>{const m=beta.exec(v);if(!m)throw Error('expected an exact beta version');return m.slice(1).map(BigInt)}
  const aa=parts(a),bb=parts(b)
  for(let i=0;i<aa.length;i++)if(aa[i]!==bb[i])return aa[i]>bb[i]?1:-1
  return 0
}
export function validateReceipt(manifest,receipt){
  compareBeta(manifest.version,manifest.version)
  for(const key of ['version','tag','repository','commit','sha256','integrity','filename','channel']){
    if(typeof manifest[key]!=='string'||manifest[key]!==receipt[key])throw Error(`release receipt mismatch: ${key}`)
  }
  if(manifest.repository!==repository||manifest.channel!=='beta'||manifest.tag!==`v${manifest.version}`||manifest.filename!==`solopup-memory-${manifest.version}.tgz`)throw Error('unexpected release identity')
  if(!/^[a-f0-9]{40}$/.test(manifest.commit)||!/^[a-f0-9]{64}$/.test(manifest.sha256)||!/^sha512-[A-Za-z0-9+/]{86}==$/.test(manifest.integrity))throw Error('invalid release digest or commit')
  if(receipt.publicDownloadVerified!==true||receipt.tarball!==`${registry}/solopup-memory/-/${manifest.filename}`||!Number.isFinite(Date.parse(receipt.publishedAt)))throw Error('verified public receipt required')
  return receipt
}
export function assertLatestUnchanged(before,after){
  if(typeof before!=='string'||typeof after!=='string'||before!==after)throw Error('npm latest changed or could not be verified; inspect manually, never restore it automatically')
}
export function assertBetaNotOlder(version,currentBeta){
  if(currentBeta!==undefined&&compareBeta(version,currentBeta)<0)throw Error('refusing to move npm beta backwards')
}

